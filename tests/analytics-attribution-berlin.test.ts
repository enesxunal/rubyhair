import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {classifyRubyTraffic} from '../src/lib/analytics-attribution';
import {berlinISODate,berlinDateKey} from '../src/lib/analytics-calendar';
import {parseAnalyticsRange,createAnalyticsReport,isoDay} from '../src/lib/admin-analytics-report';
const base='https://rubyhair.de/kollektionen/';
const ref='https://l.instagram.com/';
test('Ads are reported by fixed, non-identifying campaign source, with safe fallbacks',()=>{
 const url=(source:string,medium:string,creative='')=>base+'?utm_source='+source+'&utm_medium='+medium+'&utm_content='+creative;
 assert.equal(classifyRubyTraffic(url('meta','paid_social','instagram_post'),ref),'meta_post');
 assert.equal(classifyRubyTraffic(url('meta','paid_social','elaine_reels_15s'),ref),'meta_reels');
 assert.equal(classifyRubyTraffic(url('facebook','cpc','unexpected_click_identifier'),ref),'meta_paid');
 assert.equal(classifyRubyTraffic(url('instagram','organic','instagram_post'),ref),'social');
 assert.equal(classifyRubyTraffic(url('meta','paid_social','instagram_post'),ref,'search'),'meta_post');
 assert.equal(classifyRubyTraffic(base,'https://rubyhair.de/','meta_post'),'meta_post');
 assert.equal(classifyRubyTraffic(base,ref,'meta_reels'),'meta_reels');
 assert.equal(classifyRubyTraffic(base,'https://google.de/'),'search');
 assert.equal(classifyRubyTraffic(base,'https://facebook.com/'),'social');
 assert.equal(classifyRubyTraffic(base,'https://rubyhair.de/'),'internal');
 assert.equal(classifyRubyTraffic(base,''),'direct');
 assert.equal(classifyRubyTraffic(base,'https://other.example/'),'referral');
 assert.equal(classifyRubyTraffic(base+'?utm_source=meta&utm_medium=paid_social&utm_content=1234&fbclid=sensitive',ref),'meta_paid');
});
test('Berlin calendar day is DST aware and never changes existing UTC aggregate dates',()=>{
 assert.equal(berlinISODate(new Date('2026-11-22T22:59:59.000Z')),'2026-11-22');
 assert.equal(berlinISODate(new Date('2026-11-22T23:00:00.000Z')),'2026-11-23');
 assert.equal(berlinISODate(new Date('2026-07-01T21:59:59.000Z')),'2026-07-01');
 assert.equal(berlinISODate(new Date('2026-07-01T22:00:00.000Z')),'2026-07-02');
 assert.equal(isoDay(berlinDateKey(new Date('2026-11-22T23:25:00.000Z'))),'2026-11-23');
 assert.equal(isoDay(parseAnalyticsRange({zeitraum:'heute'},new Date('2026-11-22T23:25:00.000Z')).end),'2026-11-23');
 assert.equal(isoDay(parseAnalyticsRange({zeitraum:'gestern'},new Date('2026-11-22T23:25:00.000Z')).end),'2026-11-22');
});
test('Dashboard differentiates paid Meta ad creatives, without visitor identity or invented sessions',()=>{
 const day='2026-11-22';const now=new Date('2026-11-22T18:00:00.000Z');
 const rows=['meta_post','meta_reels','social'].map((source,i)=>({day:new Date(day+'T00:00:00.000Z'),event:'page_view',path:'/kollektionen',source,device:'mobile',count:(i+1)*3}));
 const report=createAnalyticsReport(rows,parseAnalyticsRange({zeitraum:'heute'},now),now);
 assert.equal(report.sources.find(x=>x.key==='meta_post')?.count,3);
 assert.equal(report.sources.find(x=>x.key==='meta_reels')?.count,6);
 assert.equal(report.sources.find(x=>x.key==='social')?.count,9);
 assert.ok(!('sessions' in report.current));
 const dashboard=readFileSync('app/admin/analytics/page.tsx','utf8');
 assert.ok(dashboard.includes('Werbe-Traffic nach Herkunft'));
 assert.ok(dashboard.includes('meta_post')&&dashboard.includes('meta_reels'));
 const route=readFileSync('app/api/analytics/event/route.ts','utf8');
 const track=readFileSync('src/lib/storefront-analytics.ts','utf8');
 const consent=readFileSync('src/components/analytics-consent.tsx','utf8');
 assert.ok(route.includes('request.cookies.get("ruby_analytics")?.value!=="allow"'));
 assert.ok(track.includes('if(!analyticsConsent())return'));
 assert.ok(track.includes('sessionStorage.setItem(attributionKey,result)'));
 assert.ok(consent.includes('sessionStorage.removeItem("ruby_analytics_source_tab")'));
 assert.ok(!track.includes('fbclid:something'));
});
